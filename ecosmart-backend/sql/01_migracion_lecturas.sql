-- ============================================================
-- Migración: recepción de lecturas y alertas de llenado sin duplicados
-- Ejecutar en Supabase (SQL Editor) o con psql. Se puede correr más de una vez.
-- Vocabulario de estado_alerta (el mismo que ya usaba el backend):
--   'pendiente'  alerta activa (a lo más UNA por contenedor)
--   'resuelta'   el contenedor volvió a bajar del umbral
--   'duplicada'  alertas repetidas que generaba el código anterior (se conservan, solo se marcan)
-- ============================================================

-- 1) id_alerta autogenerado, si todavía no lo es. Parte desde el máximo existente para no chocar.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'alerta_llenado'
                AND column_name = 'id_alerta' AND is_identity = 'NO' AND column_default IS NULL) THEN
    ALTER TABLE alerta_llenado ALTER COLUMN id_alerta ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(pg_get_serial_sequence('alerta_llenado', 'id_alerta'),
                   COALESCE((SELECT MAX(id_alerta) FROM alerta_llenado), 0) + 1, false);
  END IF;
END $$;

-- 2) Trazabilidad: qué porcentaje disparó la alerta y cuándo se resolvió.
ALTER TABLE alerta_llenado ADD COLUMN IF NOT EXISTS porcentaje_disparo NUMERIC(5,2);
ALTER TABLE alerta_llenado ADD COLUMN IF NOT EXISTS fecha_resolucion TIMESTAMP;

-- 3) Limpiar duplicados previos: el código anterior insertaba una alerta 'pendiente' en CADA lectura >= 80 %.
--    Se conserva la más antigua de cada contenedor y las demás se marcan 'duplicada' (no se borra nada).
UPDATE alerta_llenado a
   SET estado_alerta = 'duplicada'
 WHERE a.estado_alerta = 'pendiente'
   AND EXISTS (SELECT 1 FROM alerta_llenado b
                WHERE b.id_contenedor = a.id_contenedor
                  AND b.estado_alerta = 'pendiente'
                  AND b.id_alerta < a.id_alerta);

-- 4) CLAVE DEL "SIN DUPLICADOS": a lo más una alerta 'pendiente' por contenedor.
--    Aunque lleguen dos lecturas a la vez, la base de datos lo garantiza.
CREATE UNIQUE INDEX IF NOT EXISTS uq_alerta_pendiente_por_contenedor
  ON alerta_llenado (id_contenedor)
  WHERE estado_alerta = 'pendiente';

-- 5) Porcentaje siempre entre 0 y 100 (NOT VALID: se exige en lecturas nuevas sin revisar filas antiguas).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_contenedor_porcentaje') THEN
    ALTER TABLE contenedor
      ADD CONSTRAINT chk_contenedor_porcentaje CHECK (porcentaje_llenado BETWEEN 0 AND 100) NOT VALID;
  END IF;
END $$;

-- 6) Consultas rápidas del panel.
CREATE INDEX IF NOT EXISTS idx_alerta_estado_fecha ON alerta_llenado (estado_alerta, fecha_generacion DESC);

-- NOTA: los TIMESTAMP se guardan en UTC (el backend los escribe y lee así).
