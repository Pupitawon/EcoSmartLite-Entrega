-- ============================================================
-- Migración: registro de usuarios con Firebase
-- Ejecutar en Supabase (SQL Editor). Se puede correr más de una vez.
-- ============================================================

-- 1) id_usuario autogenerado, si todavía no lo es. Parte desde el máximo existente para no chocar.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'usuario'
                AND column_name = 'id_usuario' AND is_identity = 'NO' AND column_default IS NULL) THEN
    ALTER TABLE usuario ALTER COLUMN id_usuario ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(pg_get_serial_sequence('usuario', 'id_usuario'),
                   COALESCE((SELECT MAX(id_usuario) FROM usuario), 0) + 1, false);
  END IF;
END $$;

-- 2) Una cuenta de Firebase (id_auth = UID) corresponde a un solo usuario.
--    Los usuarios antiguos sin id_auth (NULL) no se ven afectados.
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuario_id_auth ON usuario (id_auth);
