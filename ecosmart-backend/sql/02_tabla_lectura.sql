-- ============================================================
-- Tabla de lecturas históricas de telemetría IoT
-- Ejecutar en Supabase (SQL Editor) o psql.
-- ============================================================

CREATE TABLE IF NOT EXISTS lectura (
  id_lectura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contenedor INTEGER NOT NULL REFERENCES contenedor(id_contenedor),
  porcentaje_llenado NUMERIC(5,2) NOT NULL CHECK (porcentaje_llenado BETWEEN 0 AND 100),
  fecha_lectura TIMESTAMP NOT NULL,
  fecha_recepcion TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  UNIQUE (id_contenedor, fecha_lectura)
);

CREATE INDEX IF NOT EXISTS idx_lectura_contenedor_fecha ON lectura (id_contenedor, fecha_lectura DESC);