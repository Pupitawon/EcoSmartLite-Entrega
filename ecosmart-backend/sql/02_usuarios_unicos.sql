-- ============================================================
-- Migración: registro de usuarios sin duplicados (rut, correo, id_auth)
-- Ejecutar en Supabase (SQL Editor) o con psql. Se puede correr más de una vez.
-- ============================================================

-- 1) id_usuario autogenerado, si todavía no lo es. Parte desde el máximo existente para no chocar.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'usuario'
                AND column_name = 'id_usuario' AND is_identity = 'NO' AND column_default IS NULL) THEN
    ALTER TABLE usuario ALTER COLUMN id_usuario ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(pg_get_serial_sequence('usuario', 'id_usuario'),
                   COALESCE((SELECT MAX(id_usuario) FROM usuario), 0) + 1, false);
  END IF;
END $$;

-- 2) rut único. Si ya hay duplicados, se avisa y NO se crea el índice (para no romper la migración).
DO $$
DECLARE
  n INT;
BEGIN
  SELECT count(*) INTO n FROM (SELECT rut FROM usuario GROUP BY rut HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE WARNING 'usuario.rut tiene % valor(es) duplicado(s); no se creó uq_usuario_rut. Corrige los datos y vuelve a correr esta migración.', n;
  ELSE
    CREATE UNIQUE INDEX IF NOT EXISTS uq_usuario_rut ON usuario (rut);
  END IF;
END $$;

-- 3) correo único (mismo criterio que el rut).
DO $$
DECLARE
  n INT;
BEGIN
  SELECT count(*) INTO n FROM (SELECT correo FROM usuario GROUP BY correo HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE WARNING 'usuario.correo tiene % valor(es) duplicado(s); no se creó uq_usuario_correo. Corrige los datos y vuelve a correr esta migración.', n;
  ELSE
    CREATE UNIQUE INDEX IF NOT EXISTS uq_usuario_correo ON usuario (correo);
  END IF;
END $$;

-- 4) id_auth único, solo entre quienes ya se vincularon a Firebase (puede ser NULL en cuentas antiguas).
DO $$
DECLARE
  n INT;
BEGIN
  SELECT count(*) INTO n FROM (
    SELECT id_auth FROM usuario WHERE id_auth IS NOT NULL GROUP BY id_auth HAVING count(*) > 1
  ) d;
  IF n > 0 THEN
    RAISE WARNING 'usuario.id_auth tiene % valor(es) duplicado(s); no se creó uq_usuario_id_auth. Corrige los datos y vuelve a correr esta migración.', n;
  ELSE
    CREATE UNIQUE INDEX IF NOT EXISTS uq_usuario_id_auth ON usuario (id_auth) WHERE id_auth IS NOT NULL;
  END IF;
END $$;

-- NOTA: el backend nunca guarda contraseñas ni el token de Firebase; solo el id_auth (claim "sub").
