-- ============================================================
-- Migración: reportes ciudadanos de anomalías (RF-05) visibles en el panel
-- Ejecutar en Supabase (SQL Editor) o con psql. Se puede correr más de una vez.
-- Vocabulario de estado_revision:
--   'pendiente'    recién enviado por el ciudadano
--   'en_revision'  el equipo lo está atendiendo
--   'resuelto'     se corrigió el problema
--   'descartado'   no correspondía (duplicado, falso, etc.)
-- ============================================================

-- 1) id_reporte autogenerado, si todavía no lo es. Parte desde el máximo existente para no chocar.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'reporte_anomalia'
                AND column_name = 'id_reporte' AND is_identity = 'NO' AND column_default IS NULL) THEN
    ALTER TABLE reporte_anomalia ALTER COLUMN id_reporte ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(pg_get_serial_sequence('reporte_anomalia', 'id_reporte'),
                   COALESCE((SELECT MAX(id_reporte) FROM reporte_anomalia), 0) + 1, false);
  END IF;
END $$;

-- 2) Tipo de anomalía elegido en la app (danado / residuos_incorrectos / otro) y fecha de cierre.
ALTER TABLE reporte_anomalia ADD COLUMN IF NOT EXISTS tipo_anomalia VARCHAR(30);
ALTER TABLE reporte_anomalia ADD COLUMN IF NOT EXISTS fecha_revision TIMESTAMP;
ALTER TABLE reporte_anomalia ALTER COLUMN estado_revision SET DEFAULT 'pendiente';

-- 3) Consultas rápidas del panel.
CREATE INDEX IF NOT EXISTS idx_reporte_estado_fecha ON reporte_anomalia (estado_revision, fecha_reporte DESC);

-- NOTA: los TIMESTAMP se guardan en UTC (el backend los escribe y lee así).
