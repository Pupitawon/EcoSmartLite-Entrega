-- ============================================================
-- Migración: órdenes de trabajo del panel de administración (app móvil)
-- Antes se guardaban solo en el teléfono (AsyncStorage). Ahora las comparten todos los administradores.
-- Ejecutar en Supabase (SQL Editor) o con psql. Se puede correr más de una vez.
-- Flujo de estado:
--   Pendiente → Asignada → En terreno → Ejecutada → Verificada → Cerrada
-- ============================================================

CREATE TABLE IF NOT EXISTS orden_trabajo (
  id_orden            INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  id_contenedor       INT NOT NULL REFERENCES contenedor (id_contenedor) ON DELETE CASCADE,
  tipo                VARCHAR(40) NOT NULL,
  prioridad           VARCHAR(10) NOT NULL CHECK (prioridad IN ('Alta', 'Media', 'Baja')),
  tecnico             VARCHAR(60) NOT NULL,
  estado              VARCHAR(20) NOT NULL DEFAULT 'Pendiente'
                      CHECK (estado IN ('Pendiente', 'Asignada', 'En terreno', 'Ejecutada', 'Verificada', 'Cerrada')),
  creada_por          VARCHAR(128) NOT NULL, -- UID de Firebase del administrador
  fecha_creacion      TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  fecha_actualizacion TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE INDEX IF NOT EXISTS idx_orden_estado ON orden_trabajo (estado, fecha_creacion DESC);

-- Igual que el resto de las tablas: solo el backend (rol del pool) accede; la API pública de Supabase no.
ALTER TABLE orden_trabajo ENABLE ROW LEVEL SECURITY;
