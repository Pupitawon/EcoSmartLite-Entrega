-- ============================================================
-- Migración: administradores gestionados por el súper usuario (SUPER_UIDS) desde la app.
-- Antes un administrador existía solo si su UID estaba en ADMIN_UIDS (variable de entorno).
-- Ejecutar en Supabase (SQL Editor) o con psql. Se puede correr más de una vez.
-- ============================================================

CREATE TABLE IF NOT EXISTS administrador (
  id_admin            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_auth             VARCHAR(128) NOT NULL,          -- UID de Firebase de la cuenta creada por el backend
  correo              VARCHAR(254) NOT NULL CHECK (correo = lower(correo)),
  nombre_completo     VARCHAR(100) NOT NULL,
  telefono            VARCHAR(20)  NOT NULL,          -- +569XXXXXXXX
  rut                 VARCHAR(12) NOT NULL,           -- 12345678-K
  activo              BOOLEAN NOT NULL DEFAULT TRUE,
  debe_cambiar_clave  BOOLEAN NOT NULL DEFAULT FALSE, -- true si se creó con contraseña temporal
  creado_por          VARCHAR(128) NOT NULL,          -- UID del súper usuario
  fecha_creacion      TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
  fecha_actualizacion TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_administrador_id_auth ON administrador (id_auth);
CREATE UNIQUE INDEX IF NOT EXISTS uq_administrador_correo ON administrador (correo);

-- Igual que el resto de las tablas: solo el backend (rol del pool) accede; la API pública de Supabase no.
ALTER TABLE administrador ENABLE ROW LEVEL SECURITY;

-- el rut ahora es obligatorio
UPDATE administrador SET rut = '0-0' WHERE rut IS NULL;
ALTER TABLE administrador ALTER COLUMN rut SET NOT NULL;